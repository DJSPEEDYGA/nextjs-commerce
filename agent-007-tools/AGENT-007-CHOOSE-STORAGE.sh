#!/usr/bin/env bash
# AGENT-007-CHOOSE-STORAGE.sh — Interactive drive/storage picker for Agent-007.
# Lets you choose which drive or folder to use for each data category
# (LLM models, image models, outputs, cache, logs, downloads, etc.)
# and writes .agent-007-storage-config.env so all Agent-007 scripts respect it.
#
# Usage:
#   bash AGENT-007-CHOOSE-STORAGE.sh
#   bash AGENT-007-CHOOSE-STORAGE.sh --auto   # auto-detect, no prompts
#   bash AGENT-007-CHOOSE-STORAGE.sh --list   # list drives and exit

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STAMP="$(date +%Y%m%d-%H%M%S)"

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'
RED='\033[0;31m'; BOLD='\033[1m'; NC='\033[0m'

say()  { printf '%b\n' "${CYAN}[INFO]${NC} $*"; }
ok()   { printf '%b\n' "${GREEN}[OK]${NC} $*"; }
warn() { printf '%b\n' "${YELLOW}[WARN]${NC} $*"; }
die()  { printf '%b\n' "${RED}[ERROR]${NC} $*" >&2; exit 1; }

# ── Detect mounted volumes ───────────────────────────────────────────
declare -a DRIVE_PATHS=()
declare -a DRIVE_LABELS=()
declare -a DRIVE_FREE_GB=()
declare -a DRIVE_TOTAL_GB=()

detect_drives() {
  local line mount_path free_kb total_kb free_gb total_gb label
  # macOS and Linux standard mount points
  while IFS= read -r line; do
    mount_path="$(echo "$line" | awk '{print $NF}')"
    case "$mount_path" in
      /Volumes/*|/media/*|/run/media/*|/mnt/*) ;;
      /) ;; # include root
      *) continue ;;
    esac
    total_kb="$(echo "$line" | awk '{print $2}')"
    free_kb="$(echo "$line" | awk '{print $4}')"
    [ -z "$free_kb" ] && continue
    [ "$total_kb" -lt 1048576 ] 2>/dev/null && continue  # skip < 1GB
    total_gb=$((total_kb / 1024 / 1024))
    free_gb=$((free_kb / 1024 / 1024))
    label="$(basename "$mount_path")"
    [ "$mount_path" = "/" ] && label="(internal disk)"
    DRIVE_PATHS+=("$mount_path")
    DRIVE_LABELS+=("$label")
    DRIVE_FREE_GB+=("$free_gb")
    DRIVE_TOTAL_GB+=("$total_gb")
  done < <(df -Pk 2>/dev/null | awk 'NR>1')

  # Also check for any custom path provided by the user
  if [ -n "${AGENT_007_EXTRA_DRIVE:-}" ] && [ -d "$AGENT_007_EXTRA_DRIVE" ]; then
    local ek ef et
    ek="$(df -Pk "$AGENT_007_EXTRA_DRIVE" | awk 'NR==2 {print $4}')"
    et="$(df -Pk "$AGENT_007_EXTRA_DRIVE" | awk 'NR==2 {print $2}')"
    ef=$((ek / 1024 / 1024))
    et=$((et / 1024 / 1024))
    DRIVE_PATHS+=("$AGENT_007_EXTRA_DRIVE")
    DRIVE_LABELS+=("$(basename "$AGENT_007_EXTRA_DRIVE")")
    DRIVE_FREE_GB+=("$ef")
    DRIVE_TOTAL_GB+=("$et")
  fi
}

print_drives() {
  local i
  printf '\n%b%-4s %-40s %10s %10s%b\n' "$BOLD" "#" "DRIVE / MOUNT POINT" "FREE" "TOTAL" "$NC"
  printf '%.0s─' {1..70}; printf '\n'
  for i in "${!DRIVE_PATHS[@]}"; do
    printf '  %-2s  %-40s %7s GB %7s GB\n' \
      "$((i + 1))" "${DRIVE_PATHS[$i]}" "${DRIVE_FREE_GB[$i]}" "${DRIVE_TOTAL_GB[$i]}"
  done
  printf '\n'
}

# ── Pick a drive for a category ──────────────────────────────────────
pick_drive() {
  local category="$1"
  local description="$2"
  local default_idx="${3:-1}"
  local subfolder="${4:-}"
  local choice path

  printf '%b▸ %s%b\n' "$BOLD" "$category" "$NC"
  printf '  %s\n' "$description"
  if [ -n "$subfolder" ]; then
    printf '  (subfolder: %s)\n' "$subfolder"
  fi

  while true; do
    read -r -p "  Choose drive number [${default_idx}]: " choice
    choice="${choice:-$default_idx}"
    if [[ "$choice" =~ ^[0-9]+$ ]] && (( choice >= 1 && choice <= ${#DRIVE_PATHS[@]} )); then
      path="${DRIVE_PATHS[$((choice - 1))]}"
      if [ -n "$subfolder" ]; then
        path="$path/$subfolder"
      fi
      printf '  → %s\n\n' "$path"
      echo "$path"
      return 0
    elif [ "$choice" = "c" ] || [ "$choice" = "C" ]; then
      read -r -p "  Enter custom path: " path
      if [ -n "$path" ]; then
        printf '  → %s\n\n' "$path"
        echo "$path"
        return 0
      fi
    fi
    warn "Invalid choice. Enter a number (1-${#DRIVE_PATHS[@]}) or 'c' for custom path."
  done
}

# ── Write the config ─────────────────────────────────────────────────
write_config() {
  local out="$1"
  cat > "$out" <<ENVFILE
# Agent-007 Multi-Drive Storage Configuration
# Generated by AGENT-007-CHOOSE-STORAGE.sh on $(date)
# Source this file to route Agent-007 data across your drives.
#
# To regenerate: bash AGENT-007-CHOOSE-STORAGE.sh
# To override a single category: export AGENT_007_DRIVE_xxx=/your/path before running scripts.

# ── Primary Agent-007 home (app files, tools, crew data) ─────────────
export AGENT_007_DRIVE_APP="$CHOSEN_APP"

# ── LLM model storage (Ollama models — typically the largest) ────
export AGENT_007_DRIVE_LLM_MODELS="$CHOSEN_LLM"

# ── GGUF model files (Hugging Face GGUF picks) ──────────────────
export AGENT_007_DRIVE_GGUF="$CHOSEN_GGUF"

# ── Image generation models (checkpoints, flux, loras, vae …) ───
export AGENT_007_DRIVE_IMAGE_MODELS="$CHOSEN_IMAGE_MODELS"

# ── Generated outputs (images, renders, exports) ────────────────
export AGENT_007_DRIVE_OUTPUTS="$CHOSEN_OUTPUTS"

# ── Downloads (general download targets) ────────────────────────
export AGENT_007_DRIVE_DOWNLOADS="$CHOSEN_DOWNLOADS"

# ── Cache (HF cache, pip, torch, xdg) ──────────────────────────
export AGENT_007_DRIVE_CACHE="$CHOSEN_CACHE"

# ── Logs ────────────────────────────────────────────────────────
export AGENT_007_DRIVE_LOGS="$CHOSEN_LOGS"

# ── Runtime (venvs, temp, pid files, Ollama runtime) ────────────
export AGENT_007_DRIVE_RUNTIME="$CHOSEN_RUNTIME"

# ── GOAT app data ──────────────────────────────────────────────
export AGENT_007_DRIVE_GOAT_DATA="$CHOSEN_GOAT"

# ── Backward compatibility aliases ──────────────────────────────
export FKD1_ROOT="\$AGENT_007_DRIVE_APP"
export AGENT_007_HOME="\$AGENT_007_DRIVE_APP"
export OLLAMA_MODELS="\$AGENT_007_DRIVE_LLM_MODELS"
export AGENT_007_MODEL_STORE="\$AGENT_007_DRIVE_LLM_MODELS"
export AGENT_007_GGUF_STORE="\$AGENT_007_DRIVE_GGUF"
export GOAT_DATA_ROOT="\$AGENT_007_DRIVE_GOAT_DATA"
export GOAT_DOWNLOAD_DIR="\$AGENT_007_DRIVE_DOWNLOADS"
ENVFILE
}

