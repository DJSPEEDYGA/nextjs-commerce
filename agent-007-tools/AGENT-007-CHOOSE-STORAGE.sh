# ── Print summary ────────────────────────────────────────────────────
print_summary() {
  printf '\n%b════════════════════════════════════════════════════════════%b\n' "$BOLD" "$NC"
  printf '%b  OSCAR STORAGE CONFIGURATION SUMMARY%b\n' "$BOLD" "$NC"
  printf '%b════════════════════════════════════════════════════════════%b\n' "$BOLD" "$NC"
  printf '  App / Home:        %s\n' "$CHOSEN_APP"
  printf '  LLM Models:        %s\n' "$CHOSEN_LLM"
  printf '  GGUF Models:       %s\n' "$CHOSEN_GGUF"
  printf '  Image Models:      %s\n' "$CHOSEN_IMAGE_MODELS"
  printf '  Outputs:           %s\n' "$CHOSEN_OUTPUTS"
  printf '  Downloads:         %s\n' "$CHOSEN_DOWNLOADS"
  printf '  Cache:             %s\n' "$CHOSEN_CACHE"
  printf '  Logs:              %s\n' "$CHOSEN_LOGS"
  printf '  Runtime:           %s\n' "$CHOSEN_RUNTIME"
  printf '  GOAT Data:         %s\n' "$CHOSEN_GOAT"
  printf '%b════════════════════════════════════════════════════════════%b\n\n' "$BOLD" "$NC"
}

# ── Main ─────────────────────────────────────────────────────────────
main() {
  printf '\n%b╔══════════════════════════════════════════════════════════╗%b\n' "$BOLD" "$NC"
  printf '%b║        AGENT-007 MULTI-DRIVE STORAGE CONFIGURATOR           ║%b\n' "$BOLD" "$NC"
  printf '%b╚══════════════════════════════════════════════════════════╝%b\n' "$BOLD" "$NC"
  printf '\nThis tool lets you choose which drive or folder to use for\n'
  printf 'each type of Agent-007 data. Large files (LLM models, image models)\n'
  printf 'can go on big/fast drives; small files (logs, cache) can stay local.\n'

  detect_drives

  if [ ${#DRIVE_PATHS[@]} -eq 0 ]; then
    die "No suitable drives detected. Mount a drive or set AGENT_007_EXTRA_DRIVE=/path."
  fi

  if [ "${1:-}" = "--list" ]; then
    print_drives
    exit 0
  fi

  print_drives
  printf 'Enter a drive number for each category, or %bc%b for a custom path.\n\n' "$BOLD" "$NC"

  # Find a good default (prefer FKD1 if present)
  local default_idx=1
  local i
  for i in "${!DRIVE_LABELS[@]}"; do
    if [ "${DRIVE_LABELS[$i]}" = "FKD1" ]; then
      default_idx=$((i + 1))
      break
    fi
  done

  CHOSEN_APP="$(pick_drive \
    "Agent-007 App / Home" \
    "Main Agent-007 folder: tools, crew data, scripts, web app." \
    "$default_idx" \
    "AGENT-007-ONE-FOLDER")"

  CHOSEN_LLM="$(pick_drive \
    "LLM Models (Ollama)" \
    "Ollama model blobs. 29-model pack is ~400GB. Put on your biggest/fastest drive." \
    "$default_idx" \
    "models/ollama")"

  CHOSEN_GGUF="$(pick_drive \
    "GGUF Models" \
    "Hugging Face GGUF files. Can be tens of GB." \
    "$default_idx" \
    "models/gguf")"

  CHOSEN_IMAGE_MODELS="$(pick_drive \
    "Image Models" \
    "Checkpoints, FLUX, LoRA, VAE, ControlNet, embeddings, upscalers." \
    "$default_idx" \
    "models/image")"

  CHOSEN_OUTPUTS="$(pick_drive \
    "Outputs" \
    "Generated images, renders, exports." \
    "$default_idx" \
    "outputs")"

  CHOSEN_DOWNLOADS="$(pick_drive \
    "Downloads" \
    "General download targets." \
    "$default_idx" \
    "downloads")"

  CHOSEN_CACHE="$(pick_drive \
    "Cache" \
    "HF cache, pip, torch, xdg — can grow large with model downloads." \
    "$default_idx" \
    "cache")"

  CHOSEN_LOGS="$(pick_drive \
    "Logs" \
    "Agent-007/GOAT service logs." \
    "$default_idx" \
    "logs")"

  CHOSEN_RUNTIME="$(pick_drive \
    "Runtime" \
    "Venvs, Ollama runtime, temp files, PID files." \
    "$default_idx" \
    "runtime")"

  CHOSEN_GOAT="$(pick_drive \
    "GOAT App Data" \
    "GOAT Royalty App data files." \
    "$default_idx" \
    "data")"

  print_summary

  # Write configs
  local config_out="$CHOSEN_APP/.agent-007-storage-config.env"
  write_config "$config_out"
  ok "Storage config saved: $config_out"

  # Also write a copy next to this script
  if [ "$SCRIPT_DIR" != "$CHOSEN_APP" ]; then
    write_config "$SCRIPT_DIR/.agent-007-storage-config.env"
    ok "Storage config copy: $SCRIPT_DIR/.agent-007-storage-config.env"
  fi

  create_directories
  update_one_folder_env
  update_image_runtimes_env

  printf '\n%b DONE! %b Your Agent-007 scripts will now use the drives you chose.\n' "$GREEN" "$NC"
  printf 'Config file: %s\n' "$config_out"
  printf '\nTo reconfigure later, run:\n'
  printf '  bash %s/AGENT-007-CHOOSE-STORAGE.sh\n' "$SCRIPT_DIR"
  printf '\nTo test your setup:\n'
  printf '  bash %s/TEST-AGENT-007-ONE-FOLDER.sh\n' "$CHOSEN_APP"
  printf '\n'
}

main "$@"
